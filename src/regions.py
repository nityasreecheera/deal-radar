def region_name(code: str | None) -> str | None:
    """The full name for a code, or the code itself if EDGAR's list does not have it."""
    if not code:
        return None

    return NAMES.get(code, code)


def is_us(code: str | None) -> bool:
    return code in US_STATES


# US territories EDGAR codes separately; they count as the United States.
US_TERRITORIES = frozenset({"PR", "VI", "GU", "AS", "MP", "UM"})


def country_of(code: str | None) -> str | None:
    """
    The country a code belongs to.

    A US state or territory is the United States; a Canadian province is Canada
    (EDGAR names them "Ontario, Canada"); every other code already names a
    country.
    """
    if not code:
        return None

    if code in US_STATES or code in US_TERRITORIES:
        return "United States"

    name = NAMES.get(code, code)

    if name.endswith(", Canada"):
        return "Canada"

    return name


def subdivision_of(code: str | None) -> str | None:
    """The state or province within a country, where there is one."""
    if not code:
        return None

    if code in US_STATES or code in US_TERRITORIES:
        return NAMES.get(code, code)

    name = NAMES.get(code, code)

    return name.removesuffix(", Canada") if name.endswith(", Canada") else None


def codes_in(country: str) -> list[str]:
    """Every code that belongs to a country."""
    return sorted(code for code in set(NAMES) | US_STATES if country_of(code) == country)
